-- generación: revisa los resultados con las consultas del final.
--
-- Estrategias usadas:
--   PROVEEDOR              LIST       por país (grupos regionales)
--   PRODUCTO               HASH       por id (reparto uniforme)
--   IMPORTACION            RANGE + INTERVAL mensual por fecha_registro
--   DETALLE_IMPORTACION    REFERENCE  (hereda las particiones de IMPORTACION)
--   MOVIMIENTO_INVENTARIO  RANGE + INTERVAL mensual por fecha
-- RECEPCION y DETALLE_RECEPCION las crea Hibernate al iniciar el backend.
-- =====================================================================

-- 0) Limpieza (BORRA los datos de estas tablas si ya existían)
BEGIN
  FOR t IN (SELECT column_value n FROM TABLE(sys.odcivarchar2list(
      'DETALLE_RECEPCION','RECEPCION','MOVIMIENTO_INVENTARIO','DETALLE_IMPORTACION',
      'IMPORTACION','PRODUCTO','PROVEEDOR','CATEGORIA'))) LOOP
    BEGIN EXECUTE IMMEDIATE 'DROP TABLE ' || t.n || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION WHEN OTHERS THEN NULL; END;
  END LOOP;
END;
/

-- 1) Categoría (sin particionar: tabla pequeña)
CREATE TABLE categoria (
  id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  nombre      VARCHAR2(255 CHAR) NOT NULL,
  descripcion VARCHAR2(255 CHAR),
  CONSTRAINT pk_categoria PRIMARY KEY (id),
  CONSTRAINT uk_categoria_nombre UNIQUE (nombre)
);

-- 2) Proveedor: LIST por país
CREATE TABLE proveedor (
  id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  codigo       VARCHAR2(255 CHAR) NOT NULL,
  razon_social VARCHAR2(255 CHAR) NOT NULL,
  pais         VARCHAR2(255 CHAR) NOT NULL,
  contacto     VARCHAR2(255 CHAR),
  email        VARCHAR2(255 CHAR),
  telefono     VARCHAR2(255 CHAR),
  direccion    VARCHAR2(255 CHAR),
  activo       NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT pk_proveedor PRIMARY KEY (id),
  CONSTRAINT uk_proveedor_codigo UNIQUE (codigo)
)
PARTITION BY LIST (pais) (
  PARTITION p_asia   VALUES ('China', 'Hong Kong', 'Taiwán', 'Japón', 'Corea del Sur'),
  PARTITION p_europa VALUES ('Italia', 'Alemania', 'España', 'Francia'),
  PARTITION p_otros  VALUES (DEFAULT)
)
ENABLE ROW MOVEMENT;  -- permite que una fila cambie de partición si se edita el país

-- 3) Producto: HASH por id
CREATE TABLE producto (
  id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  sku               VARCHAR2(255 CHAR) NOT NULL,
  nombre            VARCHAR2(255 CHAR) NOT NULL,
  descripcion       VARCHAR2(255 CHAR),
  categoria_id      NUMBER(19) NOT NULL,
  marca             VARCHAR2(255 CHAR),
  pais_origen       VARCHAR2(255 CHAR),
  unidad            VARCHAR2(255 CHAR),
  precio_referencia NUMBER(14,2),
  stock_minimo      NUMBER(10),
  stock_actual      NUMBER(10),
  activo            NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT pk_producto PRIMARY KEY (id),
  CONSTRAINT uk_producto_sku UNIQUE (sku),
  CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id)
)
PARTITION BY HASH (id) PARTITIONS 4;

-- 4) Importación: RANGE por fecha_registro con partición mensual automática
CREATE TABLE importacion (
  id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  numero         VARCHAR2(255 CHAR) NOT NULL,
  proveedor_id   NUMBER(19) NOT NULL,
  fecha_registro DATE NOT NULL,
  fecha_prevista DATE,
  moneda         VARCHAR2(255 CHAR),
  referencia     VARCHAR2(255 CHAR),
  estado         VARCHAR2(255 CHAR),
  observaciones  VARCHAR2(500 CHAR),
  total          NUMBER(14,2),
  CONSTRAINT pk_importacion PRIMARY KEY (id),
  CONSTRAINT uk_importacion_numero UNIQUE (numero),
  CONSTRAINT fk_imp_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedor (id)
)
PARTITION BY RANGE (fecha_registro) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH')) (
  PARTITION p_historico VALUES LESS THAN (DATE '2026-01-01')
);

-- 5) Detalle de importación: REFERENCE (sigue la partición de su importación)
CREATE TABLE detalle_importacion (
  id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  importacion_id      NUMBER(19) NOT NULL,
  producto_id         NUMBER(19) NOT NULL,
  cantidad_solicitada NUMBER(10),
  cantidad_recibida   NUMBER(10),
  precio_unitario     NUMBER(14,2),
  subtotal            NUMBER(14,2),
  observaciones       VARCHAR2(255 CHAR),
  CONSTRAINT pk_detalle_importacion PRIMARY KEY (id),
  CONSTRAINT fk_detimp_importacion FOREIGN KEY (importacion_id) REFERENCES importacion (id),
  CONSTRAINT fk_detimp_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
)
PARTITION BY REFERENCE (fk_detimp_importacion);

-- 6) Movimientos de inventario: RANGE mensual por fecha (tabla de mayor crecimiento)
CREATE TABLE movimiento_inventario (
  id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  producto_id NUMBER(19) NOT NULL,
  tipo        VARCHAR2(255 CHAR),
  cantidad    NUMBER(10),
  saldo       NUMBER(10),
  fecha       DATE NOT NULL,
  responsable VARCHAR2(255 CHAR),
  origen      VARCHAR2(255 CHAR),
  CONSTRAINT pk_movimiento PRIMARY KEY (id),
  CONSTRAINT fk_mov_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
)
PARTITION BY RANGE (fecha) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH')) (
  PARTITION p_historico VALUES LESS THAN (DATE '2026-01-01')
);

